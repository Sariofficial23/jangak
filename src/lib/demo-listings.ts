export function getDemoListing(id: string) {
  return /^-\d+$/.test(id) ? demoListings.find((item) => item.id === Number(id)) : undefined;
}

export function filterDemoListings(filters: Record<string, string | undefined>) {
  const words = (filters.q ?? "").toLocaleLowerCase().trim().split(/\s+/).filter(Boolean);
  const min = Number(filters.min) || null;
  const max = Number(filters.max) || null;
  const result = demoListings.filter((item) =>
    (!filters.cat || item.category_key === filters.cat) &&
    (!filters.region || item.region_slug === filters.region) &&
    (!filters.cond || item.condition === filters.cond) &&
    (!filters.seller || item.seller_type === filters.seller) &&
    (min === null || (item.price !== null && item.price >= min)) &&
    (max === null || (item.price !== null && item.price <= max)) &&
    words.every((word) => `${item.title} ${item.description}`.toLocaleLowerCase().includes(word)),
  );
  if (filters.sort === "cheap" || filters.sort === "expensive") {
    result.sort((a, b) => a.price === null ? (b.price === null ? 0 : 1) : b.price === null ? -1 : (a.price - b.price) * (filters.sort === "cheap" ? 1 : -1));
  }
  return result;
}
